// ============ 神煞引擎主函数 ============
// 输入：四柱数组 [['庚','午'],['辛','巳'],['乙','酉'],['癸','未']]（年月日时）+ 月支索引得季节
function lookupAll(四柱) {
  const [年柱, 月柱, 日柱, 时柱] = 四柱;
  const zhiList = 四柱.map(p => p[1]);            // 年月日时四支
  const ganList = 四柱.map(p => p[0]);            // 年月日时四干
  const 柱名 = ['年柱','月柱','日柱','时柱'];
  const 年支 = 年柱[1], 日支 = 日柱[1], 年干 = 年柱[0], 日干 = 日柱[0], 月支 = 月柱[1];
  const res = { 贵人吉神类: [], 禄刃类: [], 三合派生类: [], 孤寡类: [], 特殊贵格类: [], 婚配忌煞类: [], 直查凶煞类: [] };

  // ---- A型：日干（天乙加年干辅查）查四支 ----
  for (const [名, cfg] of Object.entries(A_TABLE)) {
    const targets = cfg.map[日干]; if (!targets) continue;
    const arr = Array.isArray(targets) ? targets : [targets];
    for (let i = 0; i < 4; i++) {
      if (arr.includes(zhiList[i])) {
        // 分类与公共库/shensha.md 大节对齐：金舆入五·特殊贵格、红艳入八·婚配忌煞，其余吉神入一
        res[名 === '十干禄' || 名 === '羊刃' ? '禄刃类' : 名 === '金舆' ? '特殊贵格类' : 名 === '红艳煞' ? '婚配忌煞类' : '贵人吉神类'].push(hit(名, 柱名[i] + zhiList[i], '日干' + 日干 + '→' + arr.join('/'), cfg.倾向, cfg.合婚用, '公共库/shensha.md' + (名 === '金舆' ? '（《三命通会·41 论金舆》）' : '')));
      }
    }
    // 天乙贵人年干辅查
    if (cfg.年干辅查 && cfg.map[年干]) {
      const arr2 = cfg.map[年干];
      for (let i = 0; i < 4; i++) {
        if (arr2.includes(zhiList[i]) && !res.贵人吉神类.some(h => h.神煞 === 名 && h.落点 === 柱名[i] + zhiList[i])) {
          res.贵人吉神类.push(hit(名 + '（年干辅查）', 柱名[i] + zhiList[i], '年干' + 年干 + '→' + arr2.join('/'), cfg.倾向 + '（辅）', cfg.合婚用, '公共库/shensha.md'));
        }
      }
    }
  }

  // ---- 月支查四干支（天德/月德/天德合/月德合）+ 四支（天医）----
  // 修复：天德四仲月（卯午酉子）值为地支（申/亥/寅/巳），须同四支比对，否则永漏
  for (const [名, cfg] of Object.entries(YUE_GAN_TABLE)) {
    const target = cfg.map[月支]; if (!target) continue;
    const 是天干 = '甲乙丙丁戊己庚辛壬癸'.includes(target);  // 判断本月查值类型
    const 比对列表 = 是天干 ? ganList : zhiList;              // 天干查四干，地支查四支
    for (let i = 0; i < 4; i++) {
      if (比对列表[i] === target) res.贵人吉神类.push(hit(名, 柱名[i] + 比对列表[i], '月支' + 月支 + '→' + target, cfg.倾向, cfg.合婚用, '《协纪辨方书》历例（公共库/shensha.md）'));
    }
  }
  const yi = TIAN_YI[月支];
  for (let i = 0; i < 4; i++) {
    if (zhiList[i] === yi) res.贵人吉神类.push(hit('天医', 柱名[i] + yi, '月支' + 月支 + '→前一位' + yi, '吉（医药有缘）', '否', '公共库/shensha.md'));
  }

  // ---- 月支查日柱（天愿/天赦）----
  const yz = TIAN_YUAN[月支];
  if (日柱[0] + 日柱[1] === yz) res.贵人吉神类.push(hit('天愿', '日柱' + yz, '月支' + 月支 + '→' + yz, '吉（嫁娶宜）', '是（择日正向）', '《协纪辨方书·天愿》'));
  const jidu = ['寅','卯','辰'].includes(月支) ? '春' : ['巳','午','未'].includes(月支) ? '夏' : ['申','酉','戌'].includes(月支) ? '秋' : '冬';
  if (日柱[0] + 日柱[1] === TIAN_SHE[jidu]) res.贵人吉神类.push(hit('天赦', '日柱' + 日柱[0] + 日柱[1], jidu + '月→' + TIAN_SHE[jidu] + '日', '吉（百事可解）', '是（择日正向）', '《三命通会》天赦日'));

  // ---- C型：三合派生（年支/日支各起查四支）----
  for (const 起支 of [年支, 日支]) {
    const ju = sanHeJu(起支); if (!ju) continue;
    for (let k = 0; k < SANHE_NAMES.length; k++) {
      const target = SANHE[ju][k];
      for (let i = 0; i < 4; i++) {
        if (zhiList[i] === target) {
          const chu = SANHE_NAMES[k].名 === '灾煞' ? '《三命通会·56 论灾煞》（公共库/shensha.md）' : '公共库/shensha.md';
          res.三合派生类.push(hit(SANHE_NAMES[k].名, 柱名[i] + target, (起支 === 年支 ? '年支' : '日支') + 起支 + '（' + ju + '）→' + target, SANHE_NAMES[k].倾向, SANHE_NAMES[k].合婚用, chu));
        }
      }
    }
  }

  // ---- D型：孤辰寡宿（年支三会局查四支）----
  for (const [ju, pair] of Object.entries(GU_GUA)) {
    if (ju.includes(年支)) {
      if (zhiList.includes(pair[0])) res.孤寡类.push(hit('孤辰', 柱名[zhiList.indexOf(pair[0])] + pair[0], '年支' + 年支 + '（' + ju + '会局）→孤辰' + pair[0], '中性（六亲缘薄·性情参断）', '是（负向·性情辅参）', '公共库/shensha.md'));
      if (zhiList.includes(pair[1])) res.孤寡类.push(hit('寡宿', 柱名[zhiList.indexOf(pair[1])] + pair[1], '年支' + 年支 + '（' + ju + '会局）→寡宿' + pair[1], '中性（六亲缘薄·性情参断）', '是（负向·性情辅参）', '公共库/shensha.md'));
      break;
    }
  }

  // ---- E型：红鸾天喜（年支查四支）----
  const hl = HONG_LUAN[年支], tx = TIAN_XI[年支];
  if (zhiList.includes(hl)) res.特殊贵格类.push(hit('红鸾', 柱名[zhiList.indexOf(hl)] + hl, '年支' + 年支 + '→红鸾' + hl, '吉（婚喜）', '是（正向）', '公共库/shensha.md'));
  if (zhiList.includes(tx)) res.特殊贵格类.push(hit('天喜', 柱名[zhiList.indexOf(tx)] + tx, '年支' + 年支 + '→天喜' + tx, '吉（婚喜）', '是（正向）', '公共库/shensha.md'));

  // ---- F型：日柱直查 ----
  const riGZ = 日柱[0] + 日柱[1];
  for (const [名, cfg] of Object.entries(RI_ZHU)) {
    if (cfg.set.includes(riGZ)) {
      const cat = 名 === '魁罡' ? '特殊贵格类' : (['孤鸾煞','八专','九丑','阴差阳错'].includes(名) ? '婚配忌煞类' : '直查凶煞类');
      res[cat].push(hit(名, '日柱' + riGZ, '日柱直查（' + riGZ + '）', cfg.倾向, cfg.合婚用, '《三命通会·总论诸神煞》（公共库/shensha.md 八/九节）'));
    }
  }

  // ---- G型：天罗地网（年支起查方向性互见）----
  if (LUO_WANG[年支]) {
    const target = LUO_WANG[年支];
    const ming = ['辰','巳'].includes(年支) ? '地网' : '天罗';
    if (zhiList.includes(target)) res.直查凶煞类.push(hit('天罗地网·' + ming, 柱名[zhiList.indexOf(target)] + target, '年支' + 年支 + '得' + target + '（' + ming + '）', '中凶（困顿牵绊）', '是（负向·磨合辅参）', '《三命通会·60 论天罗地网》'));
  }

  // ---- 空亡（日柱查四支）----
  const [k1, k2] = xunKong(riGZ);
  const kong = [];
  for (let i = 0; i < 4; i++) { if (zhiList[i] === k1 || zhiList[i] === k2) kong.push(柱名[i] + zhiList[i]); }
  if (kong.length) res.直查凶煞类.push(hit('空亡（旬空）', kong.join('、'), '日柱' + riGZ + '旬空' + k1 + k2, '中性偏凶（事悬虚待应）', '否', '公共库/干支五行.md·旬空表'));

  return res;
}

