// 求六十甲子序（甲子=0）：n%10=干序 且 n%12=支序
function gz60(gzStr) {
  const g = GAN.indexOf(gzStr[0]), z = ZHI.indexOf(gzStr[1]);
  for (let n = 0; n < 60; n++) { if (n % 10 === g && n % 12 === z) return n; }
  return -1;
}

// 日柱定旬空两支（甲子旬空戌亥……同公共库/干支五行.md 旬空表）
function xunKong(riGZ) {
  const n = gz60(riGZ), shou = n - (n % 10);
  return [ZHI[(shou + 10) % 12], ZHI[(shou + 11) % 12]];
}

// 三合局归属（支→局名）
function sanHeJu(zhi) {
  for (const ju of Object.keys(SANHE)) { if (ju.includes(zhi)) return ju; }
  return null;
}

// 命中条目构造
